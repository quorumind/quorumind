import { chosenOption, formatRange, mermaidFlowchart } from "./report.ts";
import type { Proposal } from "./schemas.ts";
import { allAnswers, type Session } from "./session.ts";

// The hand-off bundle a coding agent reads before writing the first line: CLAUDE.md for Claude Code,
// AGENTS.md for the agents that follow that convention (same instructions), and PLAN.md, the roadmap
// as checklists. The scaffolding is always in English, the lingua franca of coding agents, whatever
// the session's language; the project's own content (summary, constraints, phases) stays as written
// during the session.

export interface HandoffFile {
  path: string;
  content: string;
}

const bullets = (items: string[]) => items.map((item) => `- ${item}`).join("\n");
const checklist = (items: string[]) => items.map((item) => `- [ ] ${item}`).join("\n");
const section = (title: string, ...body: (string | false | null | undefined)[]) => {
  const content = body.filter((part): part is string => typeof part === "string" && part.trim() !== "");
  return content.length > 0 ? [`## ${title}`, "", ...content.flatMap((part) => [part, ""])] : [];
};

function architecture(proposal: Proposal): string[] {
  const components = proposal.components ?? [];
  const flows = proposal.flows ?? [];
  const names = new Map(components.map((component) => [component.id, component.label]));
  return [
    proposal.summary,
    "",
    "### Components",
    "",
    components.length > 0
      ? bullets(components.map((component) => `\`${component.id}\`: ${component.label} (${component.kind})`))
      : bullets(proposal.architecture),
    "",
    ...(flows.length > 0
      ? [
          "### Flows",
          "",
          bullets(
            flows.map(
              (flow) => `${names.get(flow.from) ?? flow.from} → ${names.get(flow.to) ?? flow.to}${flow.label ? `: ${flow.label}` : ""}`,
            ),
          ),
          "",
        ]
      : []),
    ...[mermaidFlowchart(components, flows)].filter((diagram): diagram is string => Boolean(diagram)).flatMap((diagram) => [diagram, ""]),
    "### Stack",
    "",
    bullets(proposal.stack),
    "",
    "### Infrastructure",
    "",
    bullets(proposal.infrastructure),
  ];
}

function instructions(session: Session, title: string): string {
  const sheet = session.sheet;
  const verdict = session.verdict;
  const chosen = chosenOption(session);
  const proposal = chosen?.proposal ?? null;
  const conditions = verdict?.options.find((option) => option.seat === chosen?.seat)?.conditions ?? [];
  const project = sheet?.projectName ?? session.idea;
  const lines = [
    `# ${title}`,
    "",
    `> Generated by Quorumind from decision session \`${session.id}\` (${session.updatedAt.slice(0, 10)}). Several AI models`,
    "> debated this project and an arbiter ruled. The decision report is the source of truth: if a task conflicts with it,",
    "> stop and ask instead of improvising.",
    "",
    ...section(
      "Project",
      `**${project}.** ${sheet?.summary ?? session.idea}`,
      sheet && sheet.goals.length > 0 && `Goals:\n\n${bullets(sheet.goals)}`,
      sheet && sheet.mustHave.length > 0 && `Must have:\n\n${bullets(sheet.mustHave)}`,
      sheet?.users && `Users and load: ${sheet.users}`,
      sheet?.team && `Team: ${sheet.team}`,
      sheet?.deadline && `Deadline: ${sheet.deadline}`,
    ),
    ...(proposal
      ? section(
          `Chosen architecture: ${proposal.title}`,
          architecture(proposal).join("\n"),
          verdict && `Why: ${verdict.recommendation.rationale}`,
        )
      : section(
          "Chosen architecture",
          "No option was recommended: none is feasible as it stands. Do not start building; resolve the open questions in PLAN.md with the project owner first.",
        )),
    ...section(
      "Rules: hard constraints",
      "These are non-negotiable. Never write code that violates one; if a task seems to require it, stop and ask.",
      sheet && sheet.hardConstraints.length > 0 && sheet.hardConstraints.map((rule, index) => `${index + 1}. ${rule}`).join("\n"),
      conditions.length > 0 && `The decision only holds under these conditions:\n\n${bullets(conditions)}`,
      proposal &&
        `Running cost must stay within the estimate: ${formatRange(proposal.monthlyCost, "en")} per month (${proposal.monthlyCost.basis}).`,
    ),
    ...section(
      "Out of scope",
      "Do not build these, even partially, unless the project owner asks:",
      sheet && sheet.outOfScope.length > 0
        ? bullets(sheet.outOfScope)
        : "- Nothing listed yet: ask before adding features beyond the must-haves.",
      sheet && sheet.niceToHave.length > 0 && `Nice to have, only after every phase of PLAN.md is done:\n\n${bullets(sheet.niceToHave)}`,
    ),
    ...section(
      "Conventions",
      bullets(
        [
          proposal
            ? `Use the chosen stack (${proposal.stack.join(", ")}). Ask before adding a framework, a service or a paid dependency.`
            : "",
          "Keep the components and flows above: a new component or a new flow is an architecture change, record it as an ADR in docs/decisions/.",
          ...(sheet?.softConstraints ?? []).map((constraint) => `Preference: ${constraint}`),
          ...(sheet && sheet.existingInfrastructure.length > 0
            ? [`Reuse the existing infrastructure: ${sheet.existingInfrastructure.join("; ")}.`]
            : []),
          "Never commit secrets: read keys from the environment and document each variable in the README.",
          "Every must-have gets automated tests; run the linter, the type checker and the tests before each commit.",
          "Small commits with clear messages, one concern each.",
        ].filter(Boolean),
      ),
    ),
    ...section(
      "How to work",
      [
        "1. Read PLAN.md. Work on one phase at a time, in order; never start the next phase before the current one meets its exit criterion.",
        "2. At the start of a phase, list the tasks you will do and check them against the rules and the out-of-scope list above.",
        "3. Tick the checkboxes in PLAN.md as you go, and note any deviation from the plan under the phase.",
        "4. Before a phase depends on an assumption from PLAN.md, verify it or ask; never treat an assumption as a fact.",
        "5. When an open question blocks you, stop and ask the project owner instead of choosing for them.",
      ].join("\n"),
    ),
  ];
  return `${lines.join("\n").trimEnd()}\n`;
}

function plan(session: Session): string {
  const sheet = session.sheet;
  const verdict = session.verdict;
  const chosen = chosenOption(session);
  const proposal = chosen?.proposal ?? null;
  const project = sheet?.projectName ?? session.idea;
  const lines = [
    `# Plan: ${project}`,
    "",
    proposal ? `Building **${proposal.title}**. Estimated build time: ${proposal.buildTime}.` : "No option was recommended yet.",
    "",
    "Work through the phases in order. A phase is done when every box is ticked, its exit criterion included.",
    "",
  ];
  (verdict?.roadmap ?? []).forEach((phase, index) => {
    lines.push(
      `## Phase ${index + 1}: ${phase.phase}`,
      "",
      checklist([`Deliver: ${phase.content}`, `Exit criterion met: ${phase.exitCriterion}`]),
      "",
    );
  });
  if (sheet && sheet.mustHave.length > 0) lines.push("## Must-have checklist", "", checklist(sheet.mustHave), "");
  const answered = new Set(allAnswers(session).map((answer) => answer.question));
  const questions = (verdict?.openQuestions ?? []).filter((question) => !answered.has(question));
  lines.push("## Open questions", "", questions.length > 0 ? checklist(questions) : "None recorded.", "");
  const assumptions = [
    ...(sheet?.assumptions ?? []),
    ...(proposal?.assumptions ?? []),
    ...(verdict?.claims ?? []).filter((claim) => claim.confidence !== "verified").map((claim) => `${claim.claim} (${claim.confidence})`),
  ];
  lines.push("## Assumptions to verify", "", assumptions.length > 0 ? checklist([...new Set(assumptions)]) : "None recorded.", "");
  if (verdict && verdict.risks.length > 0) {
    lines.push(
      "## Risks to watch",
      "",
      bullets(
        verdict.risks.map((risk) => `${risk.risk} (likelihood ${risk.likelihood}, impact ${risk.impact}). Mitigation: ${risk.mitigation}`),
      ),
      "",
    );
  }
  return `${lines.join("\n").trimEnd()}\n`;
}

/** CLAUDE.md, AGENTS.md and PLAN.md for a coding agent. Needs a verdict. */
export function renderHandoff(session: Session): HandoffFile[] {
  const project = session.sheet?.projectName ?? session.idea;
  const title = `${project}: instructions for coding agents`;
  const content = instructions(session, title);
  return [
    { path: "CLAUDE.md", content },
    { path: "AGENTS.md", content },
    { path: "PLAN.md", content: plan(session) },
  ];
}
